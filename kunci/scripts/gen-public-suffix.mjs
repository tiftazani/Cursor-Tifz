#!/usr/bin/env node
/**
 * Regenerates extension/public-suffix.js from the official Public Suffix List.
 *
 * The list answers one question Kunci has to get right: which part of a hostname is
 * the site, and which part anyone can register. `mail.google.com` and `google.com`
 * are the same site because `com` is a suffix. `pelindo-kpi-monitoring.surge.sh` and
 * `surge.sh` are NOT the same site, because `surge.sh` is itself a suffix: every
 * Surge customer gets their own name under it. Guessing from the last two labels
 * called the second case the same site, so one customer's saved login was offered on
 * another customer's page.
 *
 * Only rules that can change that answer are written out. A single-label rule is the
 * default case (the suffix is the last label), so it is left out; a single-label
 * WILDCARD base is not, because `*.ck` does change the answer for `foo.ck`.
 *
 * Run after a PSL update: node scripts/gen-public-suffix.mjs
 * Verify the committed file is current: node scripts/gen-public-suffix.mjs --check
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { domainToASCII } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const OUT = join(HERE, '..', 'extension', 'public-suffix.js')
const OUT_TS = join(HERE, '..', 'src', 'lib', 'public-suffix-data.ts')
const SOURCE = 'https://publicsuffix.org/list/public_suffix_list.dat'

/**
 * A browser reports `location.hostname` in punycode, so an IDN rule has to be stored
 * that way too or it can never match: the list spells the rule `公司.cn`, the page
 * says `xn--55qx5d.cn`, and comparing them is always false. A rule that cannot be
 * converted is dropped rather than kept in a form that silently never matches.
 */
function toAscii(rule) {
  if (!rule) return ''
  if (!/[^\x00-\x7f]/.test(rule)) return rule.toLowerCase()
  return domainToASCII(rule).toLowerCase()
}

async function loadList() {
  const res = await fetch(SOURCE)
  if (!res.ok) throw new Error(`PSL fetch failed: HTTP ${res.status}`)
  return res.text()
}

function parse(text) {
  const plain = new Map() // tld -> Set of sub-labels
  const wildcards = new Set()
  const exceptions = new Set()
  let dropped = 0

  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim()
    if (!line) continue
    if (line.startsWith('//')) continue

    let rule = line
    if (rule.startsWith('!')) {
      const ascii = toAscii(rule.slice(1))
      if (ascii) exceptions.add(ascii)
      continue
    }
    let isWildcard = false
    if (rule.startsWith('*.')) {
      isWildcard = true
      rule = rule.slice(2)
    }
    const ascii = toAscii(rule)
    if (!ascii) {
      dropped++
      continue
    }
    if (isWildcard) {
      // The base is what the wildcard hangs under: `*.ck` -> `ck`. A host one label
      // under the base is itself a suffix, so the base is kept even as a single label.
      wildcards.add(ascii)
      continue
    }
    if (!ascii.includes('.')) continue // a bare TLD is the default case
    const cut = ascii.lastIndexOf('.')
    const head = ascii.slice(0, cut)
    const tld = ascii.slice(cut + 1)
    if (!head) continue
    if (!plain.has(tld)) plain.set(tld, new Set())
    plain.get(tld).add(head)
  }
  return { plain, wildcards, exceptions, dropped }
}

function render({ plain, wildcards, exceptions, dropped }, { fetched }) {
  const ruleLines = [...plain.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([tld, subs]) => `${tld} ${[...subs].sort().join(' ')}`)

  const ruleCount = [...plain.values()].reduce((n, s) => n + s.size, 0)

  return `// Generated by scripts/gen-public-suffix.mjs — do not edit by hand.
// Source: ${SOURCE} (fetched ${fetched})
// ${ruleCount} plain rules, ${wildcards.size} wildcard bases, ${exceptions.size} exceptions${
    dropped ? `, ${dropped} dropped (not ASCII-convertible)` : ''
  }.
//
// Kunci needs this to tell a real site from a shared host. Guessing from the last two
// labels is wrong for every suffix that is not a bare TLD, and the wrong guess offers
// one site's saved login on another site's page.
//
// extension/site.js reads this file, and src/lib/site.ts re-exports that through a .d.ts,
// so the app build and the unpacked extension share one copy of both the data and the
// rules. tests/public-suffix.test.ts checks the rules against known hosts.

/** Date this file was generated, so a stale copy is visible. */
export const PSL_FETCHED = '${fetched}'

/**
 * Plain rules, grouped by their last label: a line \`sh botda com surge\` means
 * \`botda.sh\`, \`com.sh\` and \`surge.sh\` are all suffixes. A bare TLD is left out
 * because it is already the default answer.
 */
export const PSL_RULES = \`
${ruleLines.join('\n')}
\`

/** Bases of \`*.\` rules. A host one label under a base is itself a suffix. */
export const PSL_WILDCARDS = '${[...wildcards].sort().join(' ')}'

/** \`!\` exceptions: these are NOT suffixes even when a wildcard says they are. */
export const PSL_EXCEPTIONS = '${[...exceptions].sort().join(' ')}'
`
}

const text = await loadList()
const parsed = parse(text)
const fetched = new Date().toISOString().slice(0, 10)
const next = render(parsed, { fetched })

if (process.argv.includes('--check')) {
  // The fetch stamp changes every run, so compare the data, not the header.
  const body = (s) => s.slice(s.indexOf('export const PSL_RULES'))
  let have = ''
  try {
    have = readFileSync(OUT, 'utf8')
  } catch {
    console.error(`${OUT} is missing`)
    process.exit(1)
  }
  if (body(have) === body(next)) {
    console.log('public-suffix data is current.')
    process.exit(0)
  }
  console.error(`${OUT} is STALE. Run: node scripts/gen-public-suffix.mjs`)
  process.exit(1)
}

writeFileSync(OUT, next)
console.log(`Wrote ${OUT}`)
console.log(`  ${next.length.toLocaleString()} bytes, ${next.split('\n').length} lines`)
